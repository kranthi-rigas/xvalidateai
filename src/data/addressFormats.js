/**
 * The address shape for a country: which labels to show, whether the region is
 * a list or free text, and how the postal code is checked.
 */
export function getAddressFormat(countryCode) {
  const overrides = COUNTRY_FORMATS[countryCode] || {};
  const subdivisions = SUBDIVISIONS[countryCode] || null;

  return {
    ...DEFAULT_FORMAT,
    ...overrides,
    subdivisions,
    hasPostalCode: !NO_POSTAL_CODE.has(countryCode),
  };
}

export const countryName = (code) =>
  COUNTRIES.find(([c]) => c === code)?.[1] || code;
